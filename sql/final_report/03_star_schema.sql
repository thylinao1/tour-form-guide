-- BT5110 Project, Group 31. Task 4: star schema, built from the normalized tables (ETL).
-- PostgreSQL 18. Run after 01 and 02:  psql -d tdf -f sql/final_report/03_star_schema.sql
--
--                              dim_stage
--                                  |
--            dim_rider ------ fact_results ------ dim_team
--                               |      |
--                             dim_country
--               (two roles: country of the rider, country of the team)
--
-- Grain of fact_results: one rider on one stage (one row of RESULT).
-- Each dimension has a surrogate key (an integer generated by the warehouse). The key
-- of the normalized schema (bib number, team name, stage id, country code) is kept in
-- the dimension as an ordinary attribute.

DROP TABLE IF EXISTS fact_results, dim_rider, dim_team, dim_stage, dim_country CASCADE;

-- Dimension country: one row for each country.
CREATE TABLE dim_country (
    country_key  INTEGER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    country_code CHAR(3) NOT NULL UNIQUE,
    country_name TEXT NOT NULL
);

INSERT INTO dim_country (country_code, country_name)
SELECT country_code, country_name
FROM country
ORDER BY country_code;

-- Dimension team: the country of the team is stored in the same row (denormalized).
CREATE TABLE dim_team (
    team_key          INTEGER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    team_name         TEXT NOT NULL UNIQUE,
    team_country_code CHAR(3) NOT NULL,
    team_country_name TEXT NOT NULL
);

INSERT INTO dim_team (team_name, team_country_code, team_country_name)
SELECT t.team_name, t.team_country, c.country_name
FROM team t
JOIN country c ON c.country_code = t.team_country
ORDER BY t.team_name;

-- Dimension rider: the team, the two countries and the exit of the rider are stored in
-- the same row (denormalized). age_at_start and is_young_rider are derived from the
-- date of birth and the date of the first stage. A young rider is born on or after
-- 1 January of the race year minus 25 (the 2025 rule of the Young Rider classification).
CREATE TABLE dim_rider (
    rider_key          INTEGER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    bib_number         INTEGER NOT NULL UNIQUE,
    rider_name         TEXT NOT NULL,
    dob                DATE NOT NULL,
    age_at_start       INTEGER NOT NULL,
    is_young_rider     BOOLEAN NOT NULL,
    rider_country_code CHAR(3) NOT NULL,
    rider_country_name TEXT NOT NULL,
    team_name          TEXT NOT NULL,
    team_country_name  TEXT NOT NULL,
    finished_race      BOOLEAN NOT NULL,
    exit_stage         INTEGER,          -- empty for a rider who finished the race
    exit_reason        TEXT              -- empty for a rider who finished the race
);

INSERT INTO dim_rider (bib_number, rider_name, dob, age_at_start, is_young_rider,
                       rider_country_code, rider_country_name, team_name,
                       team_country_name, finished_race, exit_stage, exit_reason)
SELECT r.bib_number, r.rider_name, r.dob,
       EXTRACT(YEAR FROM AGE(race.start_date, r.dob))::INTEGER,
       r.dob >= MAKE_DATE(EXTRACT(YEAR FROM race.start_date)::INTEGER - 25, 1, 1),
       r.rider_country, rc.country_name, r.rider_team, tc.country_name,
       e.bib_number IS NULL, e.exit_stage, e.reason
FROM rider r
JOIN country rc ON rc.country_code = r.rider_country
JOIN team t     ON t.team_name = r.rider_team
JOIN country tc ON tc.country_code = t.team_country
LEFT JOIN exit e ON e.bib_number = r.bib_number
CROSS JOIN (SELECT MIN(date) AS start_date FROM stage) AS race
ORDER BY r.bib_number;

-- Dimension stage: the two locations and their countries are stored in the same row
-- (denormalized). race_week is derived from the rest days: a new week starts after
-- each day without a stage. The levels stage, race week and race form a hierarchy.
CREATE TABLE dim_stage (
    stage_key           INTEGER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    stage_id            INTEGER NOT NULL UNIQUE,
    stage_date          DATE NOT NULL,
    race_week           INTEGER NOT NULL,
    stage_type          TEXT NOT NULL,
    distance_km         NUMERIC NOT NULL,
    start_location      TEXT NOT NULL,
    start_country_name  TEXT NOT NULL,
    finish_location     TEXT NOT NULL,
    finish_country_name TEXT NOT NULL
);

INSERT INTO dim_stage (stage_id, stage_date, race_week, stage_type, distance_km,
                       start_location, start_country_name,
                       finish_location, finish_country_name)
SELECT s.stage_id, s.date,
       -- days since the first stage, minus race days since the first stage
       -- = rest days before this stage
       1 + (s.date - MIN(s.date) OVER ()) - (DENSE_RANK() OVER (ORDER BY s.date) - 1),
       s.type, s.distance,
       s.start_location, sc.country_name,
       s.finish_location, fc.country_name
FROM stage s
JOIN location sl ON sl.location_name = s.start_location
JOIN country sc  ON sc.country_code = sl.location_country
JOIN location fl ON fl.location_name = s.finish_location
JOIN country fc  ON fc.country_code = fl.location_country
ORDER BY s.stage_id;

-- Fact table. Measures: the three recorded times, the adjusted time (computed once,
-- when the row is loaded) and the rank. dim_country is referenced twice: once as the
-- country of the rider and once as the country of the team.
CREATE TABLE fact_results (
    rider_key         INTEGER NOT NULL REFERENCES dim_rider (rider_key),
    stage_key         INTEGER NOT NULL REFERENCES dim_stage (stage_key),
    team_key          INTEGER NOT NULL REFERENCES dim_team (team_key),
    rider_country_key INTEGER NOT NULL REFERENCES dim_country (country_key),
    team_country_key  INTEGER NOT NULL REFERENCES dim_country (country_key),
    finish_time       INTEGER NOT NULL,
    time_bonus        INTEGER NOT NULL,
    time_penalty      INTEGER NOT NULL,
    adjusted_time     INTEGER NOT NULL,
    rank              INTEGER NOT NULL,
    PRIMARY KEY (rider_key, stage_key)
);

INSERT INTO fact_results (rider_key, stage_key, team_key, rider_country_key,
                          team_country_key, finish_time, time_bonus, time_penalty,
                          adjusted_time, rank)
SELECT dr.rider_key, ds.stage_key, dt.team_key, drc.country_key, dtc.country_key,
       x.finish_time, x.time_bonus, x.time_penalty,
       x.finish_time - x.time_bonus + x.time_penalty,
       x.rank
FROM result x
JOIN dim_rider dr    ON dr.bib_number = x.bib_number
JOIN dim_stage ds    ON ds.stage_id = x.stage_id
JOIN dim_team dt     ON dt.team_name = dr.team_name
JOIN dim_country drc ON drc.country_code = dr.rider_country_code
JOIN dim_country dtc ON dtc.country_code = dt.team_country_code;

ANALYZE;
